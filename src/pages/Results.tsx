import { useMemo } from 'react';
import { Activity, Clock3, Droplets, ShieldCheck, Users, TrendingDown } from 'lucide-react';
import { Link } from 'react-router-dom';
import { CTAButton, Eyebrow, SectionHeading } from '../components/SiteChrome';
import { CheckList } from '../components/Cards';
import { ComparisonBars, Sparkline } from '../components/Charts';
import { DustMap } from '../components/Visuals';
import { computeResultsSummary } from '../features/results/resultsEngine';
import { ModelEvidenceSection } from '../features/results/ModelEvidenceSection';

function formatReductionDisplay(percent: number): string {
  if (percent > 0) return `${percent}%`;
  if (percent === 0) return '0%';
  return `${Math.abs(percent)}% increase`;
}

export default function Results() {
  const { prediction, strategyResults, summary } = useMemo(() => computeResultsSummary(), []);

  const mapReadings: [number, number, number] = [
    Math.round(prediction.sensors[0].forecastPm25),
    Math.round(prediction.sensors[1].forecastPm25),
    Math.round(prediction.sensors[3].forecastPm25),
  ];

  const noControl = strategyResults.find((s) => s.strategy === 'noControl')!;
  const continuous = strategyResults.find((s) => s.strategy === 'continuous')!;
  const reactive = strategyResults.find((s) => s.strategy === 'reactive')!;
  const predictive = strategyResults.find((s) => s.strategy === 'predictive')!;

  const pm25Bars = [{
    label: 'PM2.5',
    baseline: noControl.boundaryPm25,
    continuous: continuous.boundaryPm25,
    reactive: reactive.boundaryPm25,
    predictive: predictive.boundaryPm25,
  }];

  const pm10Bars = [{
    label: 'PM10',
    baseline: noControl.boundaryPm10,
    continuous: continuous.boundaryPm10,
    reactive: reactive.boundaryPm10,
    predictive: predictive.boundaryPm10,
  }];

  const exceedanceBars = [{
    label: 'Exceedance',
    baseline: noControl.exceedanceMinutes,
    continuous: continuous.exceedanceMinutes,
    reactive: reactive.exceedanceMinutes,
    predictive: predictive.exceedanceMinutes,
  }];

  const waterBars = [{
    label: 'Water',
    baseline: noControl.waterUsedL,
    continuous: continuous.waterUsedL,
    reactive: reactive.waterUsedL,
    predictive: predictive.waterUsedL,
  }];

  const resultMetrics = [
    {
      icon: <Activity />,
      title: 'PM Reduction',
      subtitle: 'vs No Control',
      value: formatReductionDisplay(summary.pmReductionPercent),
      foot: `${summary.noControlPm25.toFixed(1)} → ${summary.predictivePm25.toFixed(1)} µg/m³ modeled response`,
      base: 35,
    },
    {
      icon: <ShieldCheck />,
      title: 'Boundary Exceedance Reduction',
      subtitle: 'vs No Control',
      value: formatReductionDisplay(summary.exceedanceReductionPercent),
      foot: `${summary.noControlExceedance.toFixed(1)} min → ${summary.predictiveExceedance.toFixed(1)} min modeled window`,
      base: 10,
    },
    {
      icon: <Droplets />,
      title: 'Water Use Reduction',
      subtitle: 'vs Continuous Spraying',
      value: formatReductionDisplay(summary.waterReductionPercent),
      foot: `${summary.continuousWater.toFixed(1)} L → ${summary.predictiveWater.toFixed(1)} L modeled usage`,
      base: 15,
    },
    {
      icon: <Clock3 />,
      title: 'Prediction Lead Time',
      subtitle: 'Advance notice of boundary arrival',
      value: `${summary.leadTimeSeconds} sec`,
      foot: 'Derived from distance / wind velocity',
      base: 26,
    },
    {
      icon: <Users />,
      title: 'Targeted Zones Used',
      subtitle: 'Active targeted zones vs total zones',
      value: `${summary.activeZonesCount} / ${summary.totalZonesCount} zones`,
      foot: `Active: Zones ${summary.activeZoneIds.join(' & ')} for NW wind`,
      base: 50,
    },
  ];

  return (
    <>
      <section className="hero results-hero">
        <div className="hero-map-layer">
          <DustMap
            intensity={prediction.input.dustIntensity}
            activeZone={`Zone ${prediction.activeZoneIds.join(' + ')}`}
            readings={mapReadings}
          />
        </div>
        <div className="hero-copy">
          <Eyebrow><Activity size={11} /> SIMULATION RESULTS <span>•</span> SCENARIO ANALYSIS</Eyebrow>
          <h1 className="hero-title">Deterministic projections<br />for <span>cleaner air,</span><br /><span>safer communities.</span></h1>
          <p className="hero-description">Modeled dust mitigation and water conservation outputs generated by the DustTwin simulation engine under standard baseline conditions.</p>
          <div className="hero-actions"><CTAButton to="#case-study" icon={<span className="play-disc">▶</span>}>Explore Scenario</CTAButton><CTAButton to="/simulation" variant="outline" icon={<span className="cube-outline"><span /></span>}>Open Live Simulation</CTAButton></div>
        </div>
      </section>

      <section className="results-section section-wrap">
        <SectionHeading title="Scenario" highlight="Results" note="Deterministic simulation outputs under standard baseline conditions: 70% dust, 4.2 m/s NW wind, 28°C, 45% humidity." />
        <p className="disclaimer">Modeled simulation benchmark · standard baseline conditions (70% dust, 4.2 m/s NW wind, 28°C, 45% humidity).</p>
        <div className="result-metrics">
          {resultMetrics.map((metric) => <article className="result-metric" key={metric.title}><div className="result-metric-head"><span>{metric.icon}</span><div><h3>{metric.title}</h3><p>{metric.subtitle}</p></div></div><div className="result-value">{metric.value}</div><div className="result-footnote">{metric.foot}</div><div className="result-spark"><Sparkline base={metric.base} /></div></article>)}
        </div>
      </section>

      <section className="strategy-section section-wrap">
        <div className="section-heading-row">
          <h2>Strategy <span>Comparison</span></h2>
          <p>Deterministic four-strategy comparison over the shared 8-minute scenario window.</p>
          <div className="strategy-legend">
            <span><i style={{ background: '#8a929f' }} />No Control</span>
            <span><i style={{ background: '#ff723c' }} />Continuous Spraying</span>
            <span><i style={{ background: '#ffca2f' }} />Reactive Spraying</span>
            <span><i style={{ background: '#16d9ed' }} />DustTwin Predictive</span>
          </div>
        </div>
        <div className="strategy-charts">
          <article className="strategy-chart-card">
            <h3>Highest-Risk Boundary <span>PM2.5</span><small> (μg/m³)</small></h3>
            <ComparisonBars data={pm25Bars} compact />
          </article>
          <article className="strategy-chart-card">
            <h3>Highest-Risk Boundary <span>PM10</span><small> (μg/m³)</small></h3>
            <ComparisonBars data={pm10Bars} compact />
          </article>
          <article className="strategy-chart-card">
            <h3>Boundary Exceedance <span>Time</span><small> (min &gt; 40 μg/m³)</small></h3>
            <ComparisonBars data={exceedanceBars} compact />
          </article>
          <article className="strategy-chart-card">
            <h3><Droplets size={15} /> Projected <span>Water Use</span><small> (L / 8 min)</small></h3>
            <ComparisonBars data={waterBars} compact />
          </article>
        </div>
      </section>

      <ModelEvidenceSection />

      <section className="benefits-section section-wrap">
        <div><SectionHeading title="Potential" highlight="Benefits" note="Outcomes to evaluate in future field studies; not established results." /><div className="benefit-cards">
          <article className="benefit-card" style={{ backgroundImage: 'linear-gradient(100deg,rgba(3,21,34,.98),rgba(3,21,34,.77)),url(/images/site-aerial.jpg)' }}><h3>For <span>People</span></h3><CheckList items={['Healthier communities', 'Reduced dust complaints', 'Safer, more liveable neighborhoods']} /></article>
          <article className="benefit-card" style={{ backgroundImage: 'linear-gradient(100deg,rgba(3,21,34,.98),rgba(3,21,34,.75)),url(/images/tabletop-prototype.jpg)' }}><h3>For <span>Operations</span></h3><CheckList items={['Proactive, data-driven decisions', 'Lower water and operating costs', 'Compliance support and reporting']} /></article>
          <article className="benefit-card" style={{ backgroundImage: 'linear-gradient(100deg,rgba(3,21,34,.96),rgba(3,21,34,.67)),url(/images/dusty-site.jpg)' }}><h3>For the <span>Environment</span></h3><CheckList items={['Lower water use', 'Reduced air pollution', 'Smaller environmental footprint']} /></article>
        </div></div>
        <article className="case-study" id="case-study">
          <div className="case-head">
            <div>
              <h3>Scenario Preview: <span>Dust Control</span></h3>
              <small>Benchmark comparison: NW wind at 4.2 m/s, 70% dust intensity</small>
            </div>
            <Link to="/simulation" className="topic-tag">View Simulation <TrendingDown size={12} /></Link>
          </div>
          <div className="case-scenes">
            <div className="case-scene" style={{ backgroundImage: 'url(/images/dusty-site.jpg)' }}>
              <small>Baseline · No Control</small>
              <span>Unabated boundary plume ({summary.noControlPm25.toFixed(1)} µg/m³)</span>
            </div>
            <div className="case-arrow">›</div>
            <div className="case-scene" style={{ backgroundImage: 'url(/images/site-aerial.jpg)' }}>
              <small>DustTwin · Predictive</small>
              <span>Targeted Zones {summary.activeZoneIds.join(' & ')} ({summary.predictivePm25.toFixed(1)} µg/m³)</span>
            </div>
          </div>
        </article>
      </section>
    </>
  );
}
