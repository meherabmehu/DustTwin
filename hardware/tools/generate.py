"""Generate firmware definitions and assembly table from the authoritative manifest."""
import csv
import io
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / 'hardware/manifest.json'

def outputs():
    m = json.loads(MANIFEST.read_text(encoding='utf-8'))
    c, p, f = m['controllers'], m['protocol'], m['field']
    lines = ['// Generated by hardware/tools/generate.py. Edit hardware/manifest.json.', '#pragma once', '#include <stdint.h>', 'namespace Hardware {']
    for name, value in c['sensor'].items():
        lines.append(f'constexpr uint8_t {name.upper()} = {value};')
    lines += [f'constexpr uint8_t OUTPUTS[] = {{{", ".join(map(str, c["actuator"]["outputs"]))}}};', f'constexpr uint8_t OPEN_FEEDBACK[] = {{{", ".join(map(str, c["actuator"]["openFeedback"]))}}};', f'constexpr uint8_t ESTOP = {c["actuator"]["estop"]};']
    for name in ['version', 'baud', 'heartbeatMs', 'timeoutMs', 'maxLineBytes']:
        lines.append(f'constexpr unsigned long {name.upper()} = {p[name]};')
    for name, value in f.items():
        literal = 'true' if value is True else 'false' if value is False else str(value)
        lines.append(f'constexpr {"bool" if isinstance(value, bool) else "double"} {name.upper()} = {literal};')
    lines += ['}', '']
    table = io.StringIO(newline='')
    writer = csv.writer(table)
    fields = ['id', 'from', 'fromPin', 'to', 'toPin', 'voltage', 'currentRequirement', 'type', 'interface', 'isolation', 'purpose']
    writer.writerow(fields)
    for wire in m['wires']:
        writer.writerow([wire.get(key, '') for key in fields])
    return {ROOT / 'hardware/firmware/include/hardware.generated.h': '\n'.join(lines), ROOT / 'public/hardware/pin-connections.csv': table.getvalue(), ROOT / 'public/hardware/manifest.json': MANIFEST.read_text(encoding='utf-8')}

if __name__ == '__main__':
    check = '--check' in sys.argv
    stale = []
    for path, content in outputs().items():
        if check:
            if not path.exists() or path.read_text(encoding='utf-8') != content.replace('\r\n', '\n'): stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='')
    if stale: raise SystemExit('Stale generated hardware files: ' + ', '.join(stale))
    print('Hardware manifest outputs verified.' if check else 'Hardware manifest outputs generated.')
